// ===========================================
// Example 01: Hello World
// Your very first Dart program
// ===========================================

// This is where every Dart program starts.
// The computer looks for main() and begins here.

void main() {
  // print() shows text on the screen
  print('Hello, World!');

  // You can print multiple things
  print('Welcome to Dart!');
  print('This is your first program.');

  // You can print numbers too
  print(42);
  print(3.14);

  // And combine text with numbers
  print('The answer is 42');
}

// ===========================================
// Try it yourself:
// 1. Run this program
// 2. Change 'Hello, World!' to your name
// 3. Add another print statement
// 4. Try printing a calculation: print(5 + 3);
// ===========================================

// Expected output:
// Hello, World!
// Welcome to Dart!
// This is your first program.
// 42
// 3.14
// The answer is 42
